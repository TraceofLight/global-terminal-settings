#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

PERMISSION_MODES = '["acceptEdits", "bypassPermissions", "default", "dontAsk", "plan"]'
ROOT_COMMAND = "openclaude"
SUBCOMMANDS = [
    "agents",
    "auth",
    "doctor",
    "install",
    "mcp",
    "plugin",
    "plugins",
    "setup-token",
    "update",
    "upgrade",
]


def run_help(*args: str) -> str:
    result = subprocess.run([ROOT_COMMAND, *args, "--help"], check=True, capture_output=True, text=True)
    return result.stdout


def parse_options(help_text: str) -> list[tuple[str, bool]]:
    options: list[tuple[str, bool]] = []
    seen: set[str] = set()
    in_options = False
    for line in help_text.splitlines():
        stripped = line.strip()
        if stripped == "Options:":
            in_options = True
            continue
        if in_options and stripped.startswith("Commands:"):
            break
        if not in_options or not stripped.startswith("-"):
            continue
        left = re.split(r"\s{2,}", stripped, maxsplit=1)[0]
        takes_value = " <" in left or " [" in left
        for part in [piece.strip() for piece in left.split(",")]:
            if part.startswith("-"):
                token = part.split()[0]
                if token not in seen:
                    seen.add(token)
                    options.append((token, takes_value))
    return options


def render_option(token: str, takes_value: bool) -> str:
    if token == "--permission-mode":
        return f"  {token}: string@__terminal_bootstrap_openclaude_permission_modes"

    option_type = "string" if takes_value else "switch"

    if token.startswith("--"):
        return f"  {token}: {option_type}" if option_type == "string" else f"  {token}"

    return f"  {token}: {option_type}" if option_type == "string" else f"  {token}"


def render_extern(name: str, options: list[tuple[str, bool]], target_optional: bool = False) -> list[str]:
    lines = [f'extern "{name}" [']
    if name == ROOT_COMMAND:
        lines.append("  prompt?: string")
    if target_optional:
        lines.append("  target?: string")
    lines.append("  ...args: string")
    for token, takes_value in options:
        lines.append(render_option(token, takes_value))
    lines.append("]")
    return lines


def build_script() -> str:
    lines = [
        "# This file is generated by shared/nushell/generate_openclaude_integration.py.",
        "# Do not edit manually.",
        "",
        "def __terminal_bootstrap_openclaude_permission_modes [] {",
        f"  {PERMISSION_MODES}",
        "}",
        "",
    ]

    root_options = parse_options(run_help())
    lines.extend(render_extern(ROOT_COMMAND, root_options))
    lines.append("")

    for subcommand in SUBCOMMANDS:
        options = parse_options(run_help(subcommand))
        lines.extend(render_extern(f"{ROOT_COMMAND} {subcommand}", options, target_optional=(subcommand == "install")))
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    output_path = Path(args.output)
    output_path.write_text(build_script())


if __name__ == "__main__":
    main()
